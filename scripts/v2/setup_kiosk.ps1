  $signedIn = [bool](Get-Process -IncludeUserName | Where-Object UserName -like "*\$TargetUser")
  if ($signedIn) { Ok 'User present and logged on - installing in their session' }
  else { Ok "User present, not signed in - installing as $TargetUser in the background" }

  $build = Get-LatestBuild $KioskFeedUrl
  if ($RequireVersion -and $build.Version -ne [version]$RequireVersion) {
    throw "Expected v$RequireVersion, feed has v$($build.Version)"
  }
  $exe = "C:\Users\$TargetUser\AppData\Local\Programs\Kiosk\Kiosk.exe"
  $json = "C:\Users\$TargetUser\AppData\Roaming\WKG Kiosk\kiosk-identity.json"
  # the version Kiosk.exe itself reports (its file properties), e.g. 1.1.1; $null if not installed
  function Get-InstalledVersion {
    if (-not (Test-Path -LiteralPath $exe)) { return $null }
    if ("$((Get-Item -LiteralPath $exe).VersionInfo.ProductVersion)" -match '^\d+\.\d+\.\d+') { [version]$Matches[0] }
  }
  # what in the identity file differs from this run's values; the API key is compared, never shown
  function Get-IdentityMismatch {
    if (-not (Test-Path -LiteralPath $json)) { return 'no identity file' }
    $cfg = Get-Content -LiteralPath $json -Raw | ConvertFrom-Json
    if ($cfg.kioskId -cne $KioskId) { "kioskId='$($cfg.kioskId)'" }
    if ($cfg.workstationId -cne $WorkstationId) { "workstationId='$($cfg.workstationId)'" }
    if ($null -ne $cfg.apiKey -and $cfg.apiKey -cne $ApiKey) { 'a different API key' }
    if ($null -ne $cfg.apiBaseUrl -and $cfg.apiBaseUrl -ne $ApiUrl) { "apiBaseUrl='$($cfg.apiBaseUrl)'" }
    if ($null -ne $cfg.fleetSocketUrl -and $cfg.fleetSocketUrl -ne $FleetUrl) { "fleetSocketUrl='$($cfg.fleetSocketUrl)'" }
  }

  Step 'Checking the installed app'
  $installed = Get-InstalledVersion
  $mismatch = @(Get-IdentityMismatch)
  $upToDate = $installed -eq $build.Version -and -not $mismatch
  if ($upToDate) { Ok "v$installed installed, the latest; identity matches - not reinstalling" }
  elseif (-not $installed) { Ok 'Not installed yet' }
  elseif ($installed -ne $build.Version) { Ok "v$installed installed - updating to v$($build.Version)" }
  else { Ok "v$installed installed, but the identity file has $($mismatch -join ', ') - reinstalling" }

  # Interactive: runs in the user's signed-in session, no password needed (the install and the start check)
  $principal = New-ScheduledTaskPrincipal -UserId $TargetUser -LogonType Interactive -RunLevel Limited
  if ($upToDate) {
    $summary['Installer'] = 'not needed - the latest version is already installed'
  } else {
    Step "Checking $InstallerDir for the latest build"
    $InstallerPath = Join-Path $InstallerDir $build.Name
    if ((Test-Path -LiteralPath $InstallerPath) -and (Get-FileHash -LiteralPath $InstallerPath -Algorithm SHA512).Hash -eq $build.Sha512) {
      Ok "$($build.Name) already downloaded, sha512 matches latest.yml - not downloading again"
      $summary['Installer'] = "$InstallerPath (v$($build.Version), already present, sha512 verified)"
    } else {
      Step 'Downloading Kato app installer'
      New-Item -ItemType Directory -Force -Path $InstallerDir | Out-Null
      # a part-download left by an earlier run can still be held open (e.g. by antivirus), so never reuse one
      Get-ChildItem -LiteralPath $InstallerDir -Filter "$($build.Name).*download" -File | Remove-Item -Force -ErrorAction SilentlyContinue
      $partial = "$InstallerPath.$([guid]::NewGuid().ToString('N').Substring(0, 8)).download"
      Invoke-WebRequest -Uri $build.Url -OutFile $partial -UseBasicParsing
      if ((Get-FileHash -LiteralPath $partial -Algorithm SHA512).Hash -ne $build.Sha512) {
        Remove-Item -LiteralPath $partial -Force
        throw 'Downloaded installer does not match the sha512 in latest.yml'
      }
      Move-Item -LiteralPath $partial -Destination $InstallerPath -Force
      $file = Get-Item -LiteralPath $InstallerPath
      Ok ("Downloaded {0} ({1:n0} KB), sha512 matches latest.yml" -f $build.Name, ($file.Length / 1KB))

      # only the x.y.z part: a label such as 1.2.0-beta.1 or a fourth part (1.2.0.0) is not a different version
      $fileVer = "$($file.VersionInfo.ProductVersion)"
      if ($fileVer -match '^\d+\.\d+\.\d+' -and [version]$Matches[0] -ne $build.Version) {
        Warn "latest.yml says v$($build.Version) but file metadata says v$fileVer"
      }
      $summary['Installer'] = "$InstallerPath (v$($build.Version), sha512 verified)"
    }

    Step 'Registering scheduled task'
    $argLine = "/S /KIOSKID=$KioskId /WORKSTATIONID=$WorkstationId /APIKEY=$ApiKey /APIURL=$ApiUrl /FLEETURL=$FleetUrl"
    Get-ScheduledTask -TaskName $task -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
    $action = New-ScheduledTaskAction -Execute $InstallerPath -Argument $argLine
    $granted = $false
    try {
      if (-not $signedIn) {
        Import-WkgLsa
        # Without a session Windows needs the user's password: it refuses a no-password (S4U) task on these
        # kiosks, even to SYSTEM. Use the one the machine keeps for the user's automatic sign-in
        $winlogon = Get-ItemProperty -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon'
        if ("$($winlogon.AutoAdminLogon)" -ne '1' -or $winlogon.DefaultUserName -ne $TargetUser) {
          throw "$TargetUser is not signed in and does not sign in automatically, so there is no stored password - sign in as $TargetUser, then run again"
        }
        $password = if ($winlogon.DefaultPassword) { $winlogon.DefaultPassword } else { [WkgLsa]::Secret('DefaultPassword') }
        if (-not $password) { throw "No stored sign-in password for $TargetUser - sign in as $TargetUser, then run again" }
        Ok "Using $TargetUser's stored sign-in password"

        # a password task also needs 'Log on as a batch job', which standard users lack. Give it to the
        # user for the install only; the finally below takes it back
        $sid = $user.SID.Value
        if (-not [WkgLsa]::Has($sid, 'SeBatchLogonRight')) { # already has it: leave it alone
          $granted = $true # set first: if the add half-works, the finally still takes it back
          [WkgLsa]::Add($sid, 'SeBatchLogonRight')
          if (-not [WkgLsa]::Has($sid, 'SeBatchLogonRight')) { throw "Could not give $TargetUser the 'Log on as a batch job' right" }
          $summary['Rights'] = "'Log on as a batch job' given to $TargetUser for the install"
          Ok "$TargetUser may log on as a batch job (until the install is done)"
        }
      }
      # the ScheduledTasks cmdlets ignore $ErrorActionPreference (it doesn't reach their module), so say Stop on each
      if ($signedIn) { $registered = Register-ScheduledTask -TaskName $task -Action $action -Principal $principal -Force -ErrorAction Stop }
      else { $registered = Register-ScheduledTask -TaskName $task -Action $action -User $TargetUser -Password $password -RunLevel Limited -Force -ErrorAction Stop }
      $registered | Start-ScheduledTask -ErrorAction Stop
      Ok 'Task registered and started'

      Step 'Waiting for installer to start (max 15s)'
      $by = (Get-Date).AddSeconds(15)
      while (($t = Get-ScheduledTask -TaskName $task).State -ne 'Running' -and (Get-Date) -lt $by) { Start-Sleep 1 }
      if ($t.State -ne 'Running') { # not running: fine only if it already ran and finished
        $result = ($t | Get-ScheduledTaskInfo).LastTaskResult
        if ($result -ne 0) { throw ("Task did not start. LastTaskResult 0x{0:X}" -f $result) }
      }
      Ok 'Installer running'

      Step 'Waiting for task to complete (max 120s)'
      $by = (Get-Date).AddSeconds(120)
      while (($t = Get-ScheduledTask -TaskName $task).State -eq 'Running' -and (Get-Date) -lt $by) { Start-Sleep 2 }
      if ($t.State -eq 'Running') { Warn 'Install task still running at timeout' }
      else { Ok 'Task finished' }

      Step 'Waiting for setup process to exit (max 60s)'
      $setupName = [IO.Path]::GetFileNameWithoutExtension($InstallerPath)
      $by = (Get-Date).AddSeconds(60)
      while ((Get-Process -Name $setupName -ErrorAction SilentlyContinue) -and (Get-Date) -lt $by) {
        Start-Sleep 2
      }
      if (Get-Process -Name $setupName -ErrorAction SilentlyContinue) {
        Warn 'Setup still alive (likely session 0, no desktop) - stopped it'
        Get-Process -Name $setupName -ErrorAction SilentlyContinue | Stop-Process -Force
      } else {
        Ok 'Setup exited cleanly'
      }
    }
    finally {
      $password = $null
      Get-ScheduledTask -TaskName $task -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
      if ($granted) {
        try { [WkgLsa]::Remove($sid, 'SeBatchLogonRight') } catch {}
        $still = try { [WkgLsa]::Has($sid, 'SeBatchLogonRight') } catch { $true }
        if ($still) {
          Warn "$TargetUser may still have 'Log on as a batch job' - remove it in Local Security Policy > User Rights Assignment"
        } elseif ($summary['Rights']) { $summary['Rights'] += ', then taken back' }
      }
    }
  }

  Step 'Verifying install'
  if (-not (Test-Path -LiteralPath $exe)) { throw "Kiosk.exe missing at $exe" }
  $installed = Get-InstalledVersion
  if ($installed -ne $build.Version) { throw "Kiosk.exe reports v$installed after the install, expected v$($build.Version)" }
  Ok "Kiosk.exe is v$installed"

  if (-not (Test-Path -LiteralPath $json)) { throw "Not provisioned, no file at $json" }
  $mismatch = @(Get-IdentityMismatch)
  if ($mismatch) { throw "Config mismatch: $($mismatch -join '; ')" }
  $cfg = Get-Content -LiteralPath $json -Raw | ConvertFrom-Json
  $summary['App'] = "v$installed $(if ($upToDate) { 'already installed (not reinstalled)' } else { 'installed' }) for $TargetUser, identity matches $WorkstationId, printer $($cfg.printerDestination)"
  Ok 'Identity file matches'

  if (-not $signedIn) {
    # Kato needs a desktop to show on; step 3's restart signs SelfBooker in and starts it
    $summary['Launch'] = "not checked - $TargetUser was not signed in; the restart in step 3 starts Kato"
  } else {
    Step "Starting Kato as $TargetUser (30s)"
    # a bad config (e.g. wrong API endpoints) installs fine but Kato closes straight away
    function Get-Kato { @(Get-Process -Name Kiosk -IncludeUserName -ErrorAction SilentlyContinue | Where-Object UserName -like "*\$TargetUser") }
    # already running = already locked down; closing it would restart the machine (Shell Launcher action 3)
    $kato = Get-Kato
    $wasRunning = [bool]$kato
    if (-not $wasRunning) {
      Register-ScheduledTask -TaskName $task -Action (New-ScheduledTaskAction -Execute $exe) -Principal $principal -Force -ErrorAction Stop | Start-ScheduledTask -ErrorAction Stop
      Start-Sleep 30
      $kato = Get-Kato
      $kato | Stop-Process -Force # step 3's shell lock starts it for real
      Get-ScheduledTask -TaskName $task -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
    }
    if (-not $kato) { throw "Kato closed within 30s of starting - check its config and $json" }
    $summary['Launch'] = if ($wasRunning) { "Kato already running as $TargetUser (locked down), left running" } else { "Kato ran for 30s as $TargetUser, then was closed" }
    Ok 'Kato kept running'
  }

  Write-Host ""
  Write-Host ("=== SUCCESS in {0:n1}s (v{1}) ===" -f ((Get-Date)-$start).TotalSeconds, $build.Version) -ForegroundColor Green
  Show-Summary
  Write-Host "Next: 3-Shell-Lock.txt"
  Write-Host ""
  $exitCode = 0
} catch { # on the same line as the }: pasted into PowerShell 5.1, a } alone on its line runs the try without it
  Write-Host ""
  Write-Host ("=== FAILED after {0:n1}s ===" -f ((Get-Date)-$start).TotalSeconds) -ForegroundColor Red
  Write-Host $_.Exception.Message -ForegroundColor Red
  $summary['Failed at'] = $script:current
  Show-Summary
  Write-Host ""
  Get-ScheduledTask -TaskName $task -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
  $exitCode = 1
}
$exitCode
}
