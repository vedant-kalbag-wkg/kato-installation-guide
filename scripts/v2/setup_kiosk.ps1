# version, file name, URL and SHA512 (hex) of the latest build in the feed
function Get-LatestBuild($feedUrl) {
  $feedUrl = $feedUrl.TrimEnd('/') + '/'
  Step "Reading ${feedUrl}latest.yml"
  $feed = (Invoke-WebRequest -Uri "${feedUrl}latest.yml" -UseBasicParsing).Content
  if ($feed -is [byte[]]) { $feed = [Text.Encoding]::UTF8.GetString($feed) }
  $yml = @{}
  foreach ($k in 'version', 'path', 'sha512') { # top-level keys only; the files: list is indented
    if ($feed -notmatch "(?m)^${k}:\s*'?([^'\r\n]+?)'?\s*$") { throw "latest.yml has no '$k'" }
    $yml[$k] = $Matches[1]
  }
  $build = [pscustomobject]@{
    Version = [version]$yml.version
    Name = $yml.path
    Url = $feedUrl + [uri]::EscapeDataString($yml.path)
    Sha512 = [BitConverter]::ToString([Convert]::FromBase64String($yml.sha512)).Replace('-', '')
  }
  Ok "Latest is v$($build.Version): $($build.Name)"
  $build
}

# Windows' LSA calls: grant and remove one user right for one account, as Local Security Policy does
# (every other account's rights are left alone), and read the stored automatic sign-in password.
# Compiled only when needed: it takes a few seconds
function Import-WkgLsa {
  if ('WkgLsa' -as [type]) { return }
  Add-Type -TypeDefinition @"
using System;
using System.ComponentModel;
using System.Runtime.InteropServices;
using System.Security.Principal;
public static class WkgLsa {
  [StructLayout(LayoutKind.Sequential)] struct LsaString { public ushort Length, MaximumLength; public IntPtr Buffer; }
  [StructLayout(LayoutKind.Sequential)] struct LsaAttributes { public int Length; public IntPtr RootDirectory, ObjectName; public uint Attributes; public IntPtr SecurityDescriptor, SecurityQualityOfService; }
  [DllImport("advapi32.dll")] static extern uint LsaOpenPolicy(IntPtr system, ref LsaAttributes attributes, uint access, out IntPtr policy);
  [DllImport("advapi32.dll")] static extern uint LsaAddAccountRights(IntPtr policy, byte[] sid, LsaString[] rights, uint count);
  [DllImport("advapi32.dll")] static extern uint LsaRemoveAccountRights(IntPtr policy, byte[] sid, bool all, LsaString[] rights, uint count);
  [DllImport("advapi32.dll")] static extern uint LsaEnumerateAccountRights(IntPtr policy, byte[] sid, out IntPtr rights, out uint count);
  [DllImport("advapi32.dll")] static extern uint LsaRetrievePrivateData(IntPtr policy, LsaString[] key, out IntPtr data);
  [DllImport("advapi32.dll")] static extern uint LsaFreeMemory(IntPtr buffer);
  [DllImport("advapi32.dll")] static extern uint LsaClose(IntPtr policy);
  [DllImport("advapi32.dll")] static extern int LsaNtStatusToWinError(uint status);
  const uint NotFound = 0xC0000034; // the account holds no rights, or there is no such secret

  static void Check(uint status) { if (status != 0) throw new Win32Exception(LsaNtStatusToWinError(status)); }
  static byte[] Sid(string sid) { var s = new SecurityIdentifier(sid); var b = new byte[s.BinaryLength]; s.GetBinaryForm(b, 0); return b; }
  static IntPtr Open() { var a = new LsaAttributes(); IntPtr p; Check(LsaOpenPolicy(IntPtr.Zero, ref a, 0x00000815, out p)); return p; } // view, read secrets, create account, look up names
  static LsaString[] One(string right) {
    return new[] { new LsaString { Length = (ushort)(right.Length * 2), MaximumLength = (ushort)(right.Length * 2 + 2), Buffer = Marshal.StringToHGlobalUni(right) } };
  }

  public static bool Has(string sid, string right) {
    IntPtr p = Open(), list; uint n;
    try {
      uint status = LsaEnumerateAccountRights(p, Sid(sid), out list, out n);
      if (status == NotFound) return false;
      Check(status);
      try {
        int size = Marshal.SizeOf(typeof(LsaString));
        for (int i = 0; i < n; i++) {
          var r = (LsaString)Marshal.PtrToStructure(new IntPtr(list.ToInt64() + i * size), typeof(LsaString));
          if (Marshal.PtrToStringUni(r.Buffer, r.Length / 2) == right) return true;
        }
        return false;
      } finally { LsaFreeMemory(list); }
    } finally { LsaClose(p); }
  }
  public static void Add(string sid, string right) {
    IntPtr p = Open(); var r = One(right);
    try { Check(LsaAddAccountRights(p, Sid(sid), r, 1)); } finally { Marshal.FreeHGlobal(r[0].Buffer); LsaClose(p); }
  }
  public static string Secret(string name) {
    IntPtr p = Open(), data; var k = One(name);
    try {
      uint status = LsaRetrievePrivateData(p, k, out data);
      if (status == NotFound) return null;
      Check(status);
      try { var v = (LsaString)Marshal.PtrToStructure(data, typeof(LsaString)); return Marshal.PtrToStringUni(v.Buffer, v.Length / 2); }
      finally { LsaFreeMemory(data); }
    } finally { Marshal.FreeHGlobal(k[0].Buffer); LsaClose(p); }
  }
  public static void Remove(string sid, string right) {
    IntPtr p = Open(); var r = One(right);
    try { Check(LsaRemoveAccountRights(p, Sid(sid), false, r, 1)); } finally { Marshal.FreeHGlobal(r[0].Buffer); LsaClose(p); }
  }
}
"@
}

